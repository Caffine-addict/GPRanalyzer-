"""Tests for parsers/segy.py — SEG-Y radargrams as GPR software writes them."""

from __future__ import annotations

import struct
from pathlib import Path

import numpy as np
import pytest

from parsers.segy import read_segy


def write_segy(path: Path, traces: np.ndarray, interval_ps: int, spacing_mm: int, endian: str = "<",
               text: bytes = b"", xy: np.ndarray | None = None, radarmap_xy: np.ndarray | None = None) -> None:
    _, samples = traces.shape
    binary = bytearray(400)
    binary[16:18] = struct.pack(f"{endian}h", interval_ps)
    binary[20:22] = struct.pack(f"{endian}h", samples)
    binary[24:26] = struct.pack(f"{endian}h", 3)  # int16
    body = bytearray()
    for i, trace in enumerate(traces):
        header = bytearray(240)
        header[70:72] = struct.pack(f"{endian}h", -1000)
        header[80:84] = struct.pack(f"{endian}i", i * spacing_mm)
        if xy is not None:  # standard source X/Y, millimetres via the -1000 scalar
            header[72:80] = struct.pack(f"{endian}ii", *(int(v * 1000) for v in xy[i]))
        if radarmap_xy is not None:  # RadarMap: float32 northing at 170, easting at 174
            header[170:178] = struct.pack(f"{endian}ff", radarmap_xy[i][1], radarmap_xy[i][0])
        body += header + trace.astype(f"{endian}i2").tobytes()
    path.write_bytes(text.ljust(3200, b" ") + bytes(binary) + bytes(body))


@pytest.mark.parametrize("endian", ["<", ">"])
def test_reads_traces_interval_and_spacing_in_either_byte_order(tmp_path: Path, endian: str) -> None:
    traces = np.arange(3 * 8).reshape(3, 8) - 10
    path = tmp_path / "line.sgy"
    write_segy(path, traces, interval_ps=97, spacing_mm=20, endian=endian)
    line = read_segy(path)
    assert np.array_equal(line.traces, traces)
    assert line.sample_interval_ns == pytest.approx(0.097)
    assert line.trace_spacing_m == pytest.approx(0.02)


def test_a_file_that_is_not_segy_is_refused(tmp_path: Path) -> None:
    path = tmp_path / "junk.sgy"
    path.write_bytes(b"x" * 5000)
    with pytest.raises(ValueError, match="not a SEG-Y layout"):
        read_segy(path)


def test_a_truncated_file_is_refused_not_crashed(tmp_path: Path) -> None:
    path = tmp_path / "short.sgy"
    path.write_bytes(b"x" * 100)
    with pytest.raises(ValueError, match="not a SEG-Y layout"):
        read_segy(path)


def test_big_endian_is_not_mistaken_for_little_when_the_size_fits_both(tmp_path: Path) -> None:
    # 61 traces of 512 int16 samples also divide into 244-byte traces, the size a byte-swapped
    # header (512 -> 2 samples) would imply; the format code and the bounds must reject that reading.
    traces = np.arange(61 * 512, dtype=np.int64).reshape(61, 512) % 1000
    path = tmp_path / "big.sgy"
    write_segy(path, traces, interval_ps=97, spacing_mm=20, endian=">")
    line = read_segy(path)
    assert line.traces.shape == (61, 512)
    assert line.sample_interval_ns == pytest.approx(0.097)


def test_standard_source_coordinates_are_read_with_their_scalar(tmp_path: Path) -> None:
    xy = np.array([[1000.0, 2000.0], [1000.5, 2000.25], [1001.0, 2000.5]])
    path = tmp_path / "line.sgy"
    write_segy(path, np.zeros((3, 8)), interval_ps=97, spacing_mm=20, xy=xy)
    assert read_segy(path).positions_m == pytest.approx(xy)


def test_radarmap_writes_its_own_projected_coordinates(tmp_path: Path) -> None:
    # RadarMap puts NMEA floats where the standard keeps source X/Y; its grid coordinates are
    # float32 at bytes 170/174. Trusting the standard fields there would place lines nowhere.
    grid = np.array([[255025.0, 473331.25], [255025.5, 473332.0], [255026.0, 473332.75]])
    nmea = np.array([[651.0989, 5214.3369]] * 3)
    path = tmp_path / "line.sgy"
    write_segy(path, np.zeros((3, 8)), interval_ps=97, spacing_mm=20,
               text=b"generated by RadarMap 1.0", xy=nmea, radarmap_xy=grid)
    assert read_segy(path).positions_m == pytest.approx(grid, abs=0.05)


def test_a_frozen_or_missing_position_track_is_reported_as_none(tmp_path: Path) -> None:
    path = tmp_path / "line.sgy"
    write_segy(path, np.zeros((3, 8)), interval_ps=97, spacing_mm=20)
    assert read_segy(path).positions_m is None
    frozen = np.array([[255025.0, 473331.25]] * 3)
    write_segy(path, np.zeros((3, 8)), interval_ps=97, spacing_mm=20,
               text=b"RadarMap", radarmap_xy=frozen)
    assert read_segy(path).positions_m is None


def test_coordinates_that_jump_metres_per_trace_are_refused(tmp_path: Path) -> None:
    # e.g. a RadarMap file without its marker: float bytes read as integers give wild values
    wild = np.array([[1.0e5, 2.0e5], [-3.0e5, 5.0e4], [7.0e4, -9.0e4]])
    path = tmp_path / "line.sgy"
    write_segy(path, np.zeros((3, 8)), interval_ps=97, spacing_mm=20, xy=wild)
    assert read_segy(path).positions_m is None


_REAL = Path("Dataset/external/twente_utilities/01/01.1/Radargrams/Path1.sgy")


@pytest.mark.skipif(not _REAL.exists(), reason="Twente dataset not downloaded")
def test_a_real_twente_line() -> None:
    line = read_segy(_REAL)
    assert line.traces.shape == (304, 512)
    assert line.trace_spacing_m == pytest.approx(0.02)
    assert line.sample_interval_ns == pytest.approx(0.097)
    assert line.positions_m is not None  # Dutch national grid (RD New), metres
    assert line.positions_m[0] == pytest.approx([255025.06, 473331.25], abs=0.1)
